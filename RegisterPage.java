package recipemanagementpack;

import javax.swing.*;
import java.awt.*;
import java.sql.*;

public class RegisterPage extends JFrame {

    private JTextField name = new JTextField();
    private JTextField username = new JTextField();
    private JPasswordField password = new JPasswordField();
    private JPasswordField confirm = new JPasswordField();

    private JComboBox<String> role =
            new JComboBox<>(new String[]{"CUSTOMER", "CHEF"});

    public RegisterPage() {

        setTitle("Register");
        setDefaultCloseOperation(EXIT_ON_CLOSE);
        setExtendedState(MAXIMIZED_BOTH);

        BackgroundPanel outer = new BackgroundPanel("Images/welcome_bg.jpg");
        outer.setLayout(new GridBagLayout());
        outer.setBackground(AppStyle.BG);

        JPanel card = new JPanel(new GridLayout(7, 2, 12, 14));
        card.setBorder(BorderFactory.createEmptyBorder(35, 40, 35, 40));
        card.setBackground(AppStyle.CREAM);
        card.setPreferredSize(new Dimension(560, 460));

        JLabel title = new JLabel("Create Your Account", SwingConstants.CENTER);
        title.setFont(new Font("Serif", Font.BOLD, 30));
        title.setForeground(AppStyle.BROWN);

        addRow(card, "Full name", name);
        addRow(card, "Username", username);
        addRow(card, "Password", password);
        addRow(card, "Confirm password", confirm);
        addRow(card, "Register as", role);

        JButton submit = new JButton("Register");
        JButton back = new JButton("Back");

        AppStyle.styleButton(submit);
        AppStyle.styleButton(back);

        card.add(submit);
        card.add(back);

        JPanel wrap = new JPanel(new BorderLayout(8, 15));
        wrap.setBackground(AppStyle.CREAM);
        wrap.setBorder(BorderFactory.createEmptyBorder(25, 25, 25, 25));
        wrap.add(title, BorderLayout.NORTH);
        wrap.add(card, BorderLayout.CENTER);

        outer.add(wrap);
        setContentPane(outer);

        submit.addActionListener(e -> register());

        back.addActionListener(e -> {
            new recipemanagement().setVisible(true);
            dispose();
        });
    }

    private void addRow(JPanel panel, String label, JComponent field) {
        JLabel l = new JLabel(label);
        l.setFont(new Font("Segoe UI", Font.BOLD, 14));
        panel.add(l);
        panel.add(field);
    }

    private void register() {

        String n = name.getText().trim();
        String u = username.getText().trim();
        String p = new String(password.getPassword());
        String c = new String(confirm.getPassword());
        String r = (String) role.getSelectedItem();

        if (n.isEmpty() || u.isEmpty() || p.isEmpty() || c.isEmpty()) {
            msg("Please fill in every field.");
            return;
        }

        if (n.length() > 60 || u.length() > 30) {
            msg("Name or username is too long.");
            return;
        }

        if (!p.equals(c)) {
            msg("Passwords do not match.");
            return;
        }

        if (p.length() < 8 ||
                !p.matches(".*[A-Z].*") ||
                !p.matches(".*[a-z].*") ||
                !p.matches(".*\\d.*") ||
                !p.matches(".*[^A-Za-z0-9].*")) {

            msg("Password must contain at least 8 characters, uppercase, lowercase, number and special character.");
            return;
        }

        String status = r.equals("CHEF") ? "PENDING" : "ACTIVE";

        // USERID is automatically generated by Oracle.
        String sql = "INSERT INTO USERS " +
                "(NAME, USERNAME, PASSWORD, ROLE, STATUS, CREATED_ON) " +
                "VALUES (?, ?, ?, ?, ?, SYSDATE)";

        try (Connection con = DBConnection.getConnection();
                PreparedStatement ps = con.prepareStatement(sql)) {

            ps.setString(1, n);
            ps.setString(2, u);
            ps.setString(3, p);
            ps.setString(4, r);
            ps.setString(5, status);

            int result = ps.executeUpdate();

            if (result > 0) {

                JOptionPane.showMessageDialog(this,
                        r.equals("CHEF")
                        ? "Chef registration submitted! Wait for manager approval."
                        : "Registration successful! You can now log in.");

                new LoginPage().setVisible(true);
                dispose();
            }

        } catch (SQLException ex) {

            ex.printStackTrace();

            JOptionPane.showMessageDialog(this,
                    "Registration failed!\nOracle Error: " + ex.getMessage());
        }
    }

    private void msg(String message) {
        JOptionPane.showMessageDialog(this, message);
    }
}
